const dicts: Record<Locale, typeof en> = { zh, en, fr };

function lookup(obj: unknown, path: string): string {
  const val = path.split(".").reduce<unknown>((o, k) => {
    if (o && typeof o === "object" && k in (o as Record<string, unknown>)) {
      return (o as Record<string, unknown>)[k];
    }
    return undefined;
  }, obj);
  return typeof val === "string" ? val : path;
}

function cookieLocale(): Locale | null {
  if (typeof document === "undefined") return null;
  try {
    const m = document.cookie.match(/(?:^|; )dv_locale=([a-zA-Z-]+)(?:;|$)/);
    if (!m) return null;
    const raw = m[1];
    const normalized = raw.trim().replace(/_/g, "-").toLowerCase();
    if (normalized.startsWith("zh")) return "zh";
    const base = normalized.split("-")[0];
    return SUPPORTED_LOCALES.includes(base as Locale) ? (base as Locale) : null;
  } catch {
    return null;
  }
}

function persistLocale(next: Locale) {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem("locale", next);
  } catch {
    /* ignore — Safari private mode / disabled storage */
  }
  try {
    document.cookie = `dv_locale=${next}; path=/; max-age=31536000; samesite=lax`;
  } catch {
    /* ignore */
  }
}

/**
 * Resolve order: saved choice → cookie → system language.
 * Anything unsupported normalizes to English (FALLBACK_LOCALE).
 */
export function resolveInitialLocale(): Locale {
  if (typeof window === "undefined") return FALLBACK_LOCALE;
  try {
    const saved = localStorage.getItem("locale");
    if (saved) return normalizeInterfaceLanguage(saved);
  } catch {
    /* ignore — Safari private mode / disabled storage */
  }
  const fromCookie = cookieLocale();
  if (fromCookie) return fromCookie;
  return detectSystemLanguage();
}

interface LocaleContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (path: string, vars?: Record<string, string | number>) => string;
}

/** Referentially stable English fallback when rendered outside LocaleProvider. */
function fallbackTranslate(
  path: string,
  vars?: Record<string, string | number>,
): string {
  let s = lookup(dicts[FALLBACK_LOCALE], path);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

function noopSetLocale(_l: Locale) {
  /* no-op outside LocaleProvider */
}

const FALLBACK_LOCALE_VALUE: LocaleContextValue = {
  locale: FALLBACK_LOCALE,
  setLocale: noopSetLocale,
  t: fallbackTranslate,
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({
  children,
  initialLocale = FALLBACK_LOCALE,
}: {
  children: ReactNode;
  initialLocale?: Locale;
}) {
  // Must match SSR: never read localStorage/navigator during the first client render.
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    // After hydrate: prefer persisted choice, then cookie/system.
    // Do not persist here — that would stamp auto-detected (or SSR fallback en)
    // forever and block later navigator.language changes. Manual setLocale persists.
    const next = resolveInitialLocale();
    setLocaleState((prev) => (prev === next ? prev : next));
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    document.documentElement.lang = locale;
  }, [locale, ready]);

  const setLocale = useCallback((l: Locale) => {
    const next = normalizeInterfaceLanguage(l);
    setLocaleState(next);
    persistLocale(next);
  }, []);

  const t = useCallback(
    (path: string, vars?: Record<string, string | number>) => {
      const primary = dicts[locale] ?? dicts[FALLBACK_LOCALE];
      let s = lookup(primary, path);
      if (!s || s === path) {
        s = lookup(dicts[FALLBACK_LOCALE], path);
      }
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          s = s.replaceAll(`{${k}}`, String(v));
        }
      }
      return s;
    },
    [locale],
  );

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useLocale(): LocaleContextValue {
  const ctx = useContext(LocaleContext);
  if (ctx) return ctx;
  // Next.js not-found / error slots can briefly render without the client provider tree.
  // Never throw — return the module-level stable English fallback instead.
  return FALLBACK_LOCALE_VALUE;
}

export type { Locale };
